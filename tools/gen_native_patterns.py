"""Write native/src/findaddr_patterns.h: the byte patterns of client/patterns.py as C++, which the
Windows helper scans the game's code with to find its own addresses (native/README.md, "Finding
its own addresses").

    .venv/Scripts/python tools/gen_native_patterns.py [--check]

``client/patterns.py`` stays the one source: nothing in the header is typed by hand. It holds the
targets the helper takes (``native.CONFIG_KEYS``: every target the client locates but
``patterns.CLIENT_ONLY_TARGETS``, in that order), each with its patterns exactly as the client
reads them (text, the field's offset, the kind, where the instruction ends, the addend); never a
target's resolved address (``Target.rvas`` is for checks only). Run it again after any change to
``client/patterns.py``, for a new build too (docs/re/new-build.md): ``--check`` writes nothing and
exits 1 while the file differs from what this would write, and
tests/test_gen_native_patterns.py fails the same way.
"""

from __future__ import annotations

import argparse
import re
import sys

from protected import ROOT, assert_writable

sys.path.insert(0, str(ROOT))  # the client package
from client import native, patterns  # noqa: E402

OUT = ROOT / "native" / "src" / "findaddr_patterns.h"
KINDS = {"rip": "Kind::kRip", "at": "Kind::kAt"}
TOKEN = re.compile(r"^(\?\?|[0-9A-F]{2})$")

HEADER = """\
// Generated by tools/gen_native_patterns.py from client/patterns.py: do not edit by hand (a test
// fails while it is out of date). The byte patterns the helper finds the game's addresses with:
// the targets it takes (client/native.py, CONFIG_KEYS), in that order, each pattern as the client
// reads it. native/README.md, "Finding its own addresses".
#pragma once

#include "findaddr.h"

namespace zap::find {

"""


def number(value: int) -> str:
    """``value`` as a C++ integer literal: decimal for a small one, hex with its sign otherwise."""
    return str(value) if abs(value) < 10 else f"{'-' if value < 0 else ''}{abs(value):#x}"


def pattern_line(p: patterns.Pattern) -> str:
    """One pattern as an initializer. A pattern the helper cannot read is refused here, not at
    scan time: its tokens are two hex digits or ``??``, and its kind one the client accepts."""
    tokens = p.text.split()
    if not tokens or not all(TOKEN.match(t) for t in tokens):
        raise SystemExit(f"a pattern is not hex bytes and ??: {p.text}")
    if p.kind not in KINDS:
        raise SystemExit(f"a {p.kind!r} pattern is not one the client accepts: {p.text}")
    if p.kind == "rip" and not 0 <= p.disp_at <= len(tokens) - 4:
        raise SystemExit(f"a rip pattern's field is outside it: {p.text}")
    return (
        f'    {{"{" ".join(tokens)}", {p.disp_at}, {KINDS[p.kind]}, {p.rip_end}, '
        f"{number(p.addend)}}},"
    )


def render() -> str:
    """The header's text: LF line ends, the targets in ``native.CONFIG_KEYS``'s order."""
    by_name = {t.name: t for t in patterns.TARGETS}
    out = [HEADER]
    for key in native.CONFIG_KEYS:
        target = by_name[key]
        if not target.patterns:
            raise SystemExit(f"{key} has no patterns")
        out.append(f"inline constexpr Pattern k_{key}[] = {{\n")
        out.extend(pattern_line(p) + "\n" for p in target.patterns)
        out.append("};\n")
    out.append("\ninline constexpr Target kTargets[] = {\n")
    out.extend(
        f'    {{"{key}", k_{key}, {len(by_name[key].patterns)}}},\n' for key in native.CONFIG_KEYS
    )
    out.append("};\n\n}  // namespace zap::find\n")
    return "".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="write nothing; exit 1 if the file is out of date"
    )
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = OUT.read_bytes().decode("utf-8") if OUT.is_file() else None
        if current != text:
            print(f"{OUT} is out of date: run tools/gen_native_patterns.py", file=sys.stderr)
            return 1
        print(f"{OUT} is current")
        return 0
    assert_writable(OUT).write_bytes(text.encode("utf-8"))
    print(f"Wrote {OUT}: {len(native.CONFIG_KEYS)} targets")
    return 0


if __name__ == "__main__":
    sys.exit(main())
